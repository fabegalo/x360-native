"""Regenerate the shipped gamma resolve kernels; never run by normal builds.

Uses Windows SDK FXC, the pinned glslang helper, and locally built SPIRV-Tools.
All intermediates live in a temporary directory; --verify compares exact bytes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile


def run(args):
    subprocess.run([str(a) for a in args], check=True, timeout=120,
                   stdout=subprocess.DEVNULL)


def header(data, name, spirv):
    values = struct.unpack("<" + "I" * (len(data) // 4), data) if spirv else data
    lines = ["// Generated by scripts/shaders/generate_resolves.py. Do not edit.\n",
             "const " + ("uint32_t" if spirv else "unsigned char") + " " + name + "[] = {\n"]
    for start in range(0, len(values), 8 if spirv else 16):
        chunk = values[start:start + (8 if spirv else 16)]
        lines.append("    " + ", ".join(f"0x{n:08X}" if spirv else f"0x{n:02X}" for n in chunk) + ",\n")
    lines.append("};\n")
    return "".join(lines).encode()


def statistics(data, spirv):
    words = struct.unpack("<" + "I" * (len(data) // 4), data)
    if spirv:
        count, pos = 0, 5
        while pos < len(words):
            length = words[pos] >> 16
            if not length:
                raise RuntimeError("invalid SPIR-V instruction length")
            count += 1
            pos += length
        return {"spirv_instructions": count, "spirv_id_bound": words[3]}
    for offset in words[8:8 + words[7]]:
        pos = offset // 4
        if data[offset:offset + 4] == b"STAT":
            return {"dxbc_instructions": words[pos + 2], "dxbc_temps": words[pos + 3],
                    "dxbc_float_ops": words[pos + 6], "dxbc_int_ops": words[pos + 7],
                    "dxbc_uint_ops": words[pos + 8]}
    for offset in words[8:8 + words[7]]:
        if data[offset:offset + 4] not in (b"SHEX", b"SHDR"):
            continue
        start, count, temps = offset // 4 + 2, 0, 0
        pos, end = start + 2, start + words[start + 1]
        while pos < end:
            op = words[pos] & 0x7ff
            length = words[pos + 1] if op == 53 else (words[pos] >> 24) & 127
            if not length:
                raise RuntimeError("invalid DXBC token length")
            if op == 104:
                temps = words[pos + 1]
            count += 1
            pos += length
        return {"dxbc_token_instructions": count, "dxbc_temps": temps}
    return {}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--sdk-root", required=True, type=Path)
    p.add_argument("--fxc", required=True, type=Path)
    p.add_argument("--spirv-compiler", required=True, type=Path)
    p.add_argument("--spirv-tools", required=True, type=Path)
    p.add_argument("--verify", action="store_true")
    p.add_argument("--binary-dir", type=Path, help="optional local output for GPU comparisons")
    args = p.parse_args()
    shaders = args.sdk_root.resolve() / "src/graphics/shaders"
    sources = shaders / "resolve_sources"
    sha = lambda data: hashlib.sha256(data).hexdigest()
    root = Path(__file__).resolve().parents[2]
    vendored = root / "external/rexglue-sdk/thirdparty"
    # Locally linked PE files contain timestamps/build paths. Pin source
    # revisions for those tools, rather than making reproduction machine-specific.
    tool_sources = {name: subprocess.check_output(
        ["git", "-C", str(vendored / name), "rev-parse", "HEAD"], text=True).strip()
        for name in ("glslang", "spirv-tools", "spirv-headers")}
    manifest = {"sources": {f.name: sha(f.read_bytes()) for f in sorted(sources.glob("*.xesl*"))},
                "tools": {"fxc_sha256": sha(args.fxc.read_bytes()), **tool_sources,
                          "spirv_compiler_source_sha256": sha((root / "scripts/shaders/compile_resolve_spirv.cpp").read_bytes().replace(b"\r\n", b"\n")),
                          "generator_source_sha256": sha(Path(__file__).read_bytes().replace(b"\r\n", b"\n")),
                          "spirv_target": "vulkan1.0", "fxc_flags": "/T cs_5_1 /O3 /Gfp /Gis /Qstrip_reflect /Qstrip_debug /Qstrip_priv"},
                "resources": {}}
    generated = {}
    with tempfile.TemporaryDirectory(prefix="x360-resolve-") as temp:
        temp = Path(temp)
        for bpp in (8, 16, 32, 64, 128):
            for suffix in ("", "_scaled"):
                name = f"resolve_gamma_{bpp}bpp{suffix}_cs"
                source = sources / f"resolve_gamma_{bpp}bpp{suffix}.cs.xesl"
                dxbc, spv, optimized = (temp / (name + ext) for ext in (".dxbc", ".raw.spv", ".spv"))
                run([args.fxc, "/nologo", "/D", "SHADING_LANGUAGE_HLSL_XE=1", "/T", "cs_5_1",
                     "/E", "main", "/O3", "/Gfp", "/Gis", "/Qstrip_reflect", "/Qstrip_debug", "/Qstrip_priv",
                     "/Fo", dxbc, source])
                run([args.spirv_compiler, source, spv])
                run([args.spirv_tools / "spirv-opt.exe", "--target-env=vulkan1.0", "-O", "-O",
                     "--compact-ids", spv, "-o", optimized])
                run([args.spirv_tools / "spirv-val.exe", "--target-env", "vulkan1.0", optimized])
                if args.binary_dir:
                    args.binary_dir.mkdir(parents=True, exist_ok=True)
                    (args.binary_dir / (name + ".dxbc")).write_bytes(dxbc.read_bytes())
                    (args.binary_dir / (name + ".spv")).write_bytes(optimized.read_bytes())
                for directory, data, spirv in (("bytecode/d3d12_5_1", dxbc.read_bytes(), False),
                                                ("vulkan_spirv", optimized.read_bytes(), True)):
                    relative = f"{directory}/{name}.h"
                    generated[shaders / relative] = header(data, name, spirv)
                    manifest["resources"][relative] = {"binary_sha256": sha(data), "bytes": len(data),
                                                         **statistics(data, spirv)}
                print(name, "DXBC", dxbc.stat().st_size, "SPIR-V", optimized.stat().st_size, flush=True)
    generated[sources / "generated.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    for path, data in generated.items():
        if args.verify:
            if not path.is_file() or path.read_bytes() != data:
                raise RuntimeError(f"generated resource differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print("Reproducible resources verified" if args.verify else "20 gamma resolve resources generated")


if __name__ == "__main__":
    main()
